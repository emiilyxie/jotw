import pkg from "@tonejs/midi";
const { Midi } = pkg;
import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const midiPath = resolve(__dirname, "../billies-bounce.mid");
const midi = new Midi(readFileSync(midiPath));

const notes = [];
for (const track of midi.tracks) {
  for (const note of track.notes) {
    notes.push({ midi: note.midi, time: note.time, duration: note.duration });
  }
}
notes.sort((a, b) => a.time - b.time);

const totalDuration = Math.max(...notes.map((n) => n.time + n.duration));
const bpm = midi.header.tempos[0]?.bpm ?? 120;

// TypeScript for Remotion
const tsOutput = `// Auto-generated by scripts/parse-midi.mjs — do not edit by hand
export const NOTES: Array<{ midi: number; time: number; duration: number }> = ${JSON.stringify(notes, null, 2)};
export const TOTAL_DURATION_SECONDS = ${totalDuration.toFixed(3)};
export const BPM = ${bpm.toFixed(1)};
`;
writeFileSync(resolve(__dirname, "../src/notes-data.ts"), tsOutput);

// JSON for editor.html (fetched via npx serve)
const jsonOutput = JSON.stringify({ notes, totalDuration, bpm }, null, 2);
writeFileSync(resolve(__dirname, "../editor-notes.json"), jsonOutput);

console.log(`Wrote ${notes.length} notes, total ${totalDuration.toFixed(1)}s, BPM ${bpm.toFixed(1)}`);
